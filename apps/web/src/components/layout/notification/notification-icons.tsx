import type { ReactNode } from 'react';

// ── Type metadata ──────────────────────────────────────────────

export interface NotificationTypeMeta {
  bg: string;
  color: string;
  label: string;
  icon: 'shield' | 'help' | 'check' | 'bell';
}

export const NOTIFICATION_TYPE_META: Record<string, NotificationTypeMeta> = {
  permission_asked: {
    bg: 'color-mix(in srgb, var(--warning) 12%, transparent)',
    color: 'var(--warning)',
    label: '权限请求',
    icon: 'shield',
  },
  question_asked: {
    bg: 'color-mix(in srgb, var(--aux) 12%, transparent)',
    color: 'var(--aux)',
    label: '提问',
    icon: 'help',
  },
  task_update: {
    bg: 'color-mix(in srgb, var(--success) 12%, transparent)',
    color: 'var(--success)',
    label: '任务',
    icon: 'check',
  },
};

export const NOTIFICATION_TYPE_FALLBACK: NotificationTypeMeta = {
  bg: 'color-mix(in srgb, var(--fg-muted) 16%, transparent)',
  color: 'var(--fg-default)',
  label: '通知',
  icon: 'bell',
};

export function getNotificationTypeMeta(eventType: string): NotificationTypeMeta {
  return NOTIFICATION_TYPE_META[eventType] ?? NOTIFICATION_TYPE_FALLBACK;
}

